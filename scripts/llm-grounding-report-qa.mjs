import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {chromium} from '@playwright/test';
const out=path.resolve('outputs/inverse/deepseek-grounding-20261020-v1');
const file=path.join(out,'完整研究报告.html'),url=pathToFileURL(file).href;
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const result={entryPoint:'完整研究报告.html',checks:[],errors:[]};
try{
 for(const [name,width,height] of [['desktop',1440,1000],['mobile',390,844]]){
  const page=await browser.newPage({viewport:{width,height},deviceScaleFactor:1});
  page.on('pageerror',e=>result.errors.push(String(e)));
  await page.goto(url,{waitUntil:'load'});
  await page.locator('img').evaluateAll(imgs=>imgs.forEach(x=>{x.loading='eager';}));
  await page.waitForFunction(()=>[...document.images].every(x=>x.complete&&x.naturalWidth>0));
  const state=await page.evaluate(()=>({
   width:innerWidth,bodyWidth:document.documentElement.scrollWidth,
   images:[...document.images].map(i=>({source:i.getAttribute('src'),width:i.naturalWidth})),
   tableCount:document.querySelectorAll('table').length,
   mainTableRows:[...document.querySelectorAll('table')].find(t=>t.querySelector('th')&&t.textContent.includes('参数相对 MAE¹'))?.querySelectorAll('tbody tr').length,
   links:[...document.querySelectorAll('a[href]')].map(a=>a.getAttribute('href')),
   anchorsValid:[...document.querySelectorAll('a[href^="#"]')].every(a=>document.getElementById(a.getAttribute('href').slice(1))),
  }));
  if(state.bodyWidth>width+1)throw Error(`${name} page overflow ${state.bodyWidth}>${width}`);
  if(state.images.length!==5||state.mainTableRows!==48||!state.anchorsValid)throw Error('Report content inventory mismatch');
  const missing=[];
  for(const href of state.links){
   if(href.startsWith('#')||/^(https?:)/.test(href))continue;
   const p=fileURLToPath(new URL(href,url));
   if(!fs.existsSync(p)&&path.basename(p)!=='CHECKSUMS.json')missing.push(href);
  }
  if(missing.length)throw Error('Missing report links: '+missing.join(','));
  await page.screenshot({path:path.join(out,`preview-${name}.png`)});
  if(name==='desktop'){
   await page.locator('#mechanisms').scrollIntoViewIfNeeded();
   await page.screenshot({path:path.join(out,'preview-mechanisms.png')});
  }
  result.checks.push({name,viewport:[width,height],pageWidth:state.bodyWidth,
   imageCount:state.images.length,primaryTableRows:state.mainTableRows,tableCount:state.tableCount,
   missingLinks:missing,anchorsValid:true,manifestLink:'CHECKSUMS.json generated by packaging'});
  await page.close();
 }
 if(result.errors.length)throw Error('Browser errors');
 result.status='passed';
 fs.writeFileSync(path.join(out,'report-qa.json'),JSON.stringify(result,null,2));
 console.log(JSON.stringify(result));
}finally{await browser.close();}
