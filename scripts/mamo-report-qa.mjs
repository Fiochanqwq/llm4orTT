import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const out=path.resolve(process.argv[2]||'outputs/inverse/mamo-diet-20261020-v2');
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.join(out,'实验报告.html')).href);
 await expect(page.getByRole('heading',{name:'公开题目上，先看历史，再还原成本'})).toBeVisible();
 await expect(page.locator('.barrow')).toHaveCount(11);
 const before=await page.locator('#bars').innerText();
 await page.locator('#k').selectOption('20');await page.locator('#noise').selectOption('0');
 await expect(page.locator('.barrow')).toHaveCount(9);
 const after=await page.locator('#bars').innerText();
 if(before===after)throw Error('Filters did not change data');
 await expect(page.locator('#bars')).toContainText('(31/31)');
 await page.locator('#k').selectOption('10');await page.locator('#noise').selectOption('0.1');
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#download').click()]);
 await download.saveAs(path.join(out,'qa-filtered-download.json'));
 const selected=JSON.parse(fs.readFileSync(path.join(out,'qa-filtered-download.json'),'utf8'));
 if(selected.length!==341||selected.some(r=>r.K!==10||r.noise!==.1))throw Error('Downloaded rows mismatch');
 const missingImages=await page.locator('img').evaluateAll(imgs=>imgs.some(i=>!i.complete||i.naturalWidth===0));
 if(missingImages)throw Error('Missing report figure');
 await page.evaluate(()=>scrollTo(0,0));
 await page.screenshot({path:path.join(out,'报告首页.png')});
 await page.screenshot({path:path.join(out,'报告预览.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'手机预览.png'),fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 if(errors.length)throw Error(errors.join('\n'));
 const result={status:'passed',checks:['10 original methods + 1 supplementary control','9 methods at non-primary conditions','condition filters','341 exact download records','figure loaded','desktop and mobile layouts','no browser errors']};
 fs.writeFileSync(path.join(out,'report-qa.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
}finally{await browser.close()}
